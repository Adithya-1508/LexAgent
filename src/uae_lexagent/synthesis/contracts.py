"""Data contracts and protocols for legal synthesis and citation verification."""

from __future__ import annotations

from decimal import Decimal
from enum import Enum
from typing import Protocol

from pydantic import BaseModel, ConfigDict, Field

from ..models import Jurisdiction, Language, LegalEvidence, LegalQuery


class VerificationStatus(str, Enum):
    """Rigorous status assigned by the CitationVerifier gate."""

    VERIFIED = "verified"
    UNVERIFIED = "unverified"
    CONTRADICTED = "contradicted"
    ABSTAINED = "abstained"


class DraftLegalClaim(BaseModel):
    """An unverified statutory claim generated by a synthesizer."""

    model_config = ConfigDict(extra="forbid")

    claim_id: str = Field(min_length=1)
    claim_key: str = Field(min_length=1)
    conclusion: str = Field(min_length=1)
    cited_alignment_ids: list[str] = Field(default_factory=list)
    confidence: Decimal = Field(default=Decimal("1.0"), ge=0, le=1)


class VerifiedLegalClaim(DraftLegalClaim):
    """A claim that has passed or failed the statutory verification gate."""

    verification_status: VerificationStatus
    verification_reasons: list[str] = Field(default_factory=list)
    support_score: float = Field(default=1.0, ge=0.0, le=1.0)


class GeneratedLegalAnswer(BaseModel):
    """Draft synthesis output prior to verification gate."""

    model_config = ConfigDict(extra="forbid")

    answer_id: str = Field(min_length=1)
    query: LegalQuery
    jurisdiction: Jurisdiction
    answerable: bool
    summary: str
    claims: list[DraftLegalClaim] = Field(default_factory=list)
    full_text: str = ""
    referenced_evidence: list[LegalEvidence] = Field(default_factory=list)
    abstention_reason: str | None = None
    generation_latency_ms: float = 0.0


class GroundedLegalAnswer(BaseModel):
    """Final verified legal response with rendered text and provenance."""

    model_config = ConfigDict(extra="forbid")

    answer_id: str = Field(min_length=1)
    query: LegalQuery
    jurisdiction: Jurisdiction
    answerable: bool
    verification_status: VerificationStatus
    summary: str
    claims: list[VerifiedLegalClaim] = Field(default_factory=list)
    full_text: str = ""
    referenced_evidence: list[LegalEvidence] = Field(default_factory=list)
    abstention_reason: str | None = None
    generation_latency_ms: float = 0.0
    verification_latency_ms: float = 0.0


class GeneratorProtocol(Protocol):
    """Shared protocol implemented by all synthesis generators."""

    def generate(
        self,
        query: LegalQuery,
        evidence: list[LegalEvidence],
        jurisdiction: Jurisdiction,
        language: Language,
    ) -> GeneratedLegalAnswer: ...
